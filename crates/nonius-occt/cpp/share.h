// Общие грани двух версий детали. Внутренний заголовок прослойки, не часть C-интерфейса.

#ifndef NONIUS_SHARE_H
#define NONIUS_SHARE_H

#include <TopoDS_Shape.hxx>

namespace nonius {

// Сделать одинаковые грани, рёбра и вершины двух версий одними и теми же
// объектами: `was` — копия `before`, `now` — `after`, где совпавшее заменено
// объектами из `was`. Форма тел не меняется, но булевым операциям не нужно
// заново пересекать одинаковые грани — сравнение версий, где изменилась малая
// часть, идёт в разы быстрее. false — совпадений нет или результат не прошёл
// проверку; тогда `was` и `now` — исходные тела.
//
// Почему не готовый режим склейки OpenCascade (BOPAlgo_Options::SetGlue): он
// требует, чтобы грани тел только совпадали и не пересекались, а у изменённой
// детали они пересекаются (карман прорезает верхнюю грань) — на пластине Test
// склейка дала неверный объём.
bool share_faces(const TopoDS_Shape& before, const TopoDS_Shape& after, TopoDS_Shape* was,
                 TopoDS_Shape* now);

}  // namespace nonius

#endif
