//! Разбор папки: человек показывает папку, где модели, чертежи и бумаги
//! лежат вперемешку, а Nonius предлагает, как разложить её в проект.
//!
//! Три шага, и между ними — решение человека (в коде шаг 1 и 2 можно
//! сделать разом: [`App::intake_plan`]):
//! 0. [`App::intake_study`] изучает папку — это долгая часть. Из
//!    [`IntakeStudy`] план получается мгновенно: `study.plan(ответы)`.
//! 1. План ([`IntakePlan`]) ничего не меняет: какие будут детали и сборки,
//!    какие файлы — версии одной детали, какой чертёж к какой детали, что
//!    осталось непонятым. У каждого решения записано «почему», а там, где
//!    программа не уверена, — вопрос человеку (`questions.rs`). Ответил —
//!    план пересчитан.
//! 2. [`App::intake_apply`] выполняет план: копирует файлы в проект и
//!    сохраняет версии. Исходная папка не меняется.
//!
//! План — обычные данные: его одинаково показывают окно, команда
//! `nonius intake` и ИИ, а править его может и человек, и программа.
//! Будущий аддин SolidWorks спросит то же самое про один файл.
//!
//! Откуда берутся догадки:
//! - одно имя с разными расширениями (`вал.sldprt`, `вал.step`, `вал.pdf`) —
//!   одна деталь;
//! - чертёж идёт к модели, на которую он ссылается (точка `LinkSource`,
//!   отвечает SolidWorks), даже если назван иначе;
//! - `вал`, `вал_v2`, `вал (3)` — версии одной детали (`names.rs`), но не
//!   тогда, когда оба файла стоят в одной сборке: это разные детали;
//! - одно имя в разных папках (проект скопировали целиком) — та же деталь,
//!   если файлы одинаковые, и её версии, если форма похожа;
//! - догадку по именам проверяет форма (`shape.rs`): похожие — версии,
//!   непохожие — разные детали, одинаковые — возможно, копии;
//! - детали, которые нужны только одной сборке, кладутся в её папку.
//!
//! Файлы: здесь — данные плана, `study.rs` — изучение папки (обход, связи),
//! `units.rs` — модель и её бумаги, `names.rs` — пометки версий в именах,
//! `grouping.rs` — какие модели одна деталь и как её назвать, `split.rs` —
//! чему верить (сборка, человек, форма, имя), `shape.rs` — сравнение формы, `measure.rs` — откуда берётся форма (паспорт STEP, для
//! файла SolidWorks — через модуль перевода), `memory.rs` — память о форме
//! между разборами, `hints.rs` — похожие детали
//! с разными именами, `words.rs` — что изменилось между версиями словами,
//! `look.rs` — две модели в 3D («Показать в 3D»),
//! `questions.rs` — вопросы и ответы, `plan.rs` — сам
//! план, `apply.rs` — выполнение.

